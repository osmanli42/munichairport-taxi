export type DriverKey = keyof typeof D;
const IDX: Record<Lang, number> = { de: 0, tr: 1, en: 2 };

export function driverT(lang: Lang) {
  return (k: DriverKey): string => D[k][IDX[lang] ?? 0];
}

export function statusKey(s: string): DriverKey {
  return (`status_${s}` in D ? `status_${s}` : 'status_assigned') as DriverKey;
}
